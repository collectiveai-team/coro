"""Export one scrape of ``GET /metrics`` as a file, for ``promtool check metrics``.

The exposition is generated by the running app, so there is nothing tracked to
lint: like ``export_contracts.py``, this writes it out first. The app is given a
runtime whose ASR Adapter carries a real admission controller, so every coro
metric family appears in the scrape; no model is loaded.

Usage::

    python scripts/export_metrics.py <output-file>
"""

from __future__ import annotations

import sys
from collections.abc import Sequence
from pathlib import Path

import cyclopts
from rich.console import Console

_out = Console(markup=False, emoji=False, highlight=False, soft_wrap=True)


class _AdmittedASR:
    """The least an ASR Adapter needs for its admission state to be published."""

    honours_prompt = False

    def __init__(self) -> None:
        from coro.backends.asr.concurrency import AdmissionController

        self.admission = AdmissionController(max_concurrency=2, max_queue_depth=4)

    async def transcribe_pcm(self, pcm: bytes, *, language=None, prompt=None) -> list:
        """Never called: the export only scrapes."""
        return []


def scrape_metrics() -> str:
    """Return the text exposition ``GET /metrics`` serves for a warmed-up server."""
    from fastapi.testclient import TestClient

    from coro.app import create_app
    from coro.runtime import RuntimeState

    application = create_app()
    application.state.runtime = RuntimeState(asr_adapter=_AdmittedASR(), warmup_ready=True)
    response = TestClient(application).get("/metrics")
    response.raise_for_status()
    return response.text


app = cyclopts.App(
    name="export_metrics",
    help=__doc__,
    version_flags=(),
    help_format="plaintext",
    default_parameter=cyclopts.Parameter(negative=()),
)


@app.default
def _export(output_file: Path, /) -> None:
    """Write one scrape of the metrics endpoint to ``output_file``.

    Args:
        output_file: File to write the text exposition into.

    """
    output_file.parent.mkdir(parents=True, exist_ok=True)
    output_file.write_text(scrape_metrics(), encoding="utf-8")
    _out.out(f"exported {output_file} ({output_file.stat().st_size} bytes)")


def main(argv: Sequence[str] | None = None) -> int:
    """Write one scrape of the metrics endpoint to the requested file."""
    app(argv)
    return 0


if __name__ == "__main__":
    sys.exit(main())
