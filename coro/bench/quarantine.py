"""Quarantine for circular (self-generated) reference material.

A **Reference STM** must be human- or corpus-authored. The project previously
produced Spanish figures by scoring the server against a reference that was
itself generated by the system under test, which makes every metric circular and
meaningless. This module refuses to let such material enter a **Quality
Benchmark** again.

Two things are rejected:

* anything under a quarantined directory (the legacy self-generated Spanish
  ground-truth tree), and
* anything named like a **Hypothesis STM** (``*.hyp.stm``), which is the shape a
  self-generated reference always takes.

The check is intentionally loud: a benchmark that silently scores against its own
output is worse than one that does not run.
"""

from __future__ import annotations

from pathlib import Path

QUARANTINED_REFERENCE_DIRS: tuple[str, ...] = (
    "benchmark/groundtruth",
    "benchmark/ground_truth",
)
"""Directories holding legacy self-generated reference material."""

SELF_GENERATED_REFERENCE_SUFFIXES: tuple[str, ...] = (".hyp.stm",)
"""Filename suffixes that identify a Hypothesis STM masquerading as a reference."""


class CircularReferenceError(RuntimeError):
    """Raised when a reference STM is (or may be) self-generated output."""

    def __init__(self, path: Path, reason: str) -> None:
        super().__init__(
            f"Refusing to score against quarantined reference {path}: {reason}. "
            "A Reference STM must come from a human or corpus annotation, never "
            "from this system's own output. Use --spanish-preset for a public "
            "Spanish Workload Set, or --ami-preset for English."
        )
        self.path = path
        self.reason = reason


def reference_quarantine_reason(path: Path) -> str | None:
    """Return why ``path`` is quarantined, or None when it is scorable.

    Args:
        path: Candidate reference STM path.

    Returns:
        A human-readable reason string, or None when the reference may be used.

    """
    posix = path.as_posix().lower()
    for fragment in QUARANTINED_REFERENCE_DIRS:
        if fragment in posix:
            return f"it lives under the quarantined {fragment}/ tree"
    for suffix in SELF_GENERATED_REFERENCE_SUFFIXES:
        if posix.endswith(suffix):
            return f"its name ends with {suffix}, the Hypothesis STM naming convention"
    return None


def assert_scorable_reference(path: Path) -> None:
    """Raise :class:`CircularReferenceError` when ``path`` is quarantined."""
    reason = reference_quarantine_reason(path)
    if reason is not None:
        raise CircularReferenceError(path, reason)
